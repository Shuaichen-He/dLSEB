"""
Forward Run with Estimated Parameters (No Optimization)
---------------------------------------------------------
Loads pre-estimated parameters from .npy files (generated by
3.parameter_estimate.py), runs the dLSEB model for a 10-day simulation
without any optimization, and saves EB_result.npy / T_result.npy.

Usage
-----
Single site:
    python run_estimation.py --site Huazhaizi

All 3 sites:
    python run_estimation.py --all
"""

import os
import sys
import argparse

import jax.numpy as jnp

# ---------------------------------------------------------------------------
# Resolve repo root & register as a package root
# ---------------------------------------------------------------------------
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "..", ".."))
DLSEB_DIR = os.path.join(REPO_ROOT, "dLSEB")

# REPO_ROOT: enables "from dLSEB.xxx import ..." (package-style imports)
# DLSEB_DIR:  compat for dLSEB internal "from config/from data_loader" imports
sys.path.insert(0, REPO_ROOT)
sys.path.insert(1, DLSEB_DIR)

DATA_BASE = os.path.join(REPO_ROOT, "data", "2.data_selection")
PARAMS_DIR = os.path.join(REPO_ROOT, "data", "3.estimate_parameters")
OUTPUT_DIR = SCRIPT_DIR  # Save output in this experiment folder

SITES = ["Huazhaizi", "Ejin", "Shenshawo"]

SPIN_UP_DAYS = 20  # Spin-up iterations (same as main.py)

# ---------------------------------------------------------------------------
# Must be set BEFORE importing equinox / optimistix (inside dLSEB model)
# ---------------------------------------------------------------------------
if "EQX_ON_ERROR" not in os.environ:
    os.environ["EQX_ON_ERROR"] = "nan"

from dLSEB.model.energy_balence import spin_up_soil_T, scan_training_periods


# =============================================================================
# Data loader (site-aware; replaces dLSEB's data_loader.py which uses ../)
# =============================================================================
def load_site_data(site_name):
    """Load meteorological, soil, and EC data for a given site.

    Reads meteo_var.csv, soil.csv, ec_var.csv, air_constants.csv from
    DATA_BASE/{site_name}/ and assembles JAX arrays matching the dLSEB format.
    """
    import pandas as pd

    site_dir = os.path.join(DATA_BASE, site_name)

    data = pd.read_csv(os.path.join(site_dir, "meteo_var.csv"))
    soil_data = pd.read_csv(os.path.join(site_dir, "soil.csv"))
    flux = pd.read_csv(os.path.join(site_dir, "ec_var.csv"))
    air_constant = pd.read_csv(os.path.join(site_dir, "air_constants.csv"))

    # Air density
    rho = air_constant["rho"].astype(float).values

    # Meteorological forcing
    Rsd = data["DR"].astype(float).values
    Rld = data["DLR_Cor"].astype(float).values
    T_atm = data["Ta_5m"].astype(float).values + 273.15  # K
    u = flux["Wnd"].astype(float).values
    P = data["Press"].astype(float).values  # hPa

    # Specific humidity [kg/kg] (H2O in g/m³ → kg/kg)
    q_atm = flux["H2O"].astype(float).values / 1000.0

    meteo_input = jnp.array([Rsd, Rld, T_atm, q_atm, u, rho, P])

    # Observation constraints (not used for forward run, but needed for T_sfc)
    Rsu = jnp.where(
        data["UR"].astype(float).values > 0, data["UR"].astype(float).values, 0.0
    )
    Rlu = data["ULR_Cor"].astype(float).values
    Hs = flux["Hs"].astype(float).values
    G = -1 * jnp.array([
        soil_data["Gs_1"].astype(float).values,
        soil_data["Gs_2"].astype(float).values,
        soil_data["Gs_3"].astype(float).values,
    ]).mean(axis=0)

    # Surface temperature [K]
    T_sfc = jnp.array(soil_data["Ts_0cm"].astype(float).values).T + 273.15

    # Soil temperature at 4 depths [K] (for Train_T)
    Train_T = (
        jnp.array([
            soil_data["Ts_2cm"].astype(float).values,
            soil_data["Ts_4cm"].astype(float).values,
            soil_data["Ts_10cm"].astype(float).values,
            soil_data["Ts_20cm"].astype(float).values,
        ]).T
        + 273.15
    )

    return {
        "meteo_input": meteo_input,
        "Train_T": Train_T,
        "Rsu": Rsu,
        "Rlu": Rlu,
        "Hs": Hs,
        "G": G,
        "T_sfc": T_sfc,
    }


# =============================================================================
# Load estimated parameters from .npy
# =============================================================================
def load_params(site_name):
    """Load pre-estimated parameters for a site.

    Returns (alpha, sigma, z0m, k, C) as Python floats (non-JAX scalars).
    """
    import numpy as np

    npy_path = os.path.join(PARAMS_DIR, f"{site_name}.npy")
    params_dict = np.load(npy_path, allow_pickle=True).item()

    alpha = float(params_dict["alpha"])
    sigma = float(params_dict["sigma"])
    z0m = float(params_dict["z0m"])
    k = float(params_dict["k"])
    C = float(params_dict["C"])

    return alpha, sigma, z0m, k, C


# =============================================================================
# Forward simulation (no training)
# =============================================================================
def run_simulation(site_name):
    """Run 10-day dLSEB forward simulation using pre-estimated parameters."""
    print(f"\n{'='*60}")
    print(f"  Site: {site_name}")
    print(f"{'='*60}")

    # Load parameters & data
    alpha, sigma, z0m, k, C = load_params(site_name)
    data = load_site_data(site_name)

    meteo_input = data["meteo_input"]
    Train_T = data["Train_T"]

    logC = jnp.log(C)

    print(f"  α   = {alpha:.4f}")
    print(f"  σ   = {sigma:.4f}")
    print(f"  z₀ₘ = {z0m:.4e} m")
    print(f"  k   = {k:.4f} W m^{{-1}} K^{{-1}}")
    print(f"  C   = {C:.2e} J m^{{-3}} K^{{-1}}")

    # Spin-up
    print(f"  Spinning up for {SPIN_UP_DAYS} iterations...")
    spin_up_T0 = spin_up_soil_T(
        alpha, sigma, z0m, k, logC, meteo_input, Train_T, SPIN_UP_DAYS
    )
    print(f"  Spin-up done. T0 = {spin_up_T0[:4]}")

    # 10-day simulation
    print("  Running 10-day simulation...")
    r_s, r_l, H, G_out, T_surface, T_result = scan_training_periods(
        alpha, sigma, z0m, k, logC, meteo_input, spin_up_T0
    )

    # Save results
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    eb_path = os.path.join(OUTPUT_DIR, f"EB_result_{site_name}.npy")
    t_path = os.path.join(OUTPUT_DIR, f"T_result_{site_name}.npy")

    jnp.save(eb_path, jnp.array([r_s, r_l, H, G_out]))
    jnp.save(t_path, jnp.array(T_result))

    print(f"  [✓] EB_result saved: {eb_path}")
    print(f"  [✓] T_result saved:  {t_path}")

    return {
        "site": site_name,
        "Rsu": r_s,
        "Rlu": r_l,
        "H": H,
        "G": G_out,
        "T_surface": T_surface,
        "T_soil": T_result,
    }


# =============================================================================
# CLI entry point
# =============================================================================
if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="dLSEB forward simulation with pre-estimated parameters."
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--site", type=str,
        help="Run a single site (Huazhaizi, Ejin, Shenshawo)",
    )
    group.add_argument(
        "--all", action="store_true",
        help="Run all 3 sites",
    )
    args = parser.parse_args()

    if args.all:
        for site in SITES:
            run_simulation(site)
    else:
        if args.site not in SITES:
            print(f"Error: unknown site '{args.site}'. Choose from {SITES}")
            sys.exit(1)
        run_simulation(args.site)
